// Letra que ainda não existe na fonte aparece como '?'
function getGlyph(font, char) {
  return font.glyphs[char.toUpperCase()] ?? font.glyphs['?']
}

// Largura do texto em pixels, contando o espaço entre as letras.
export function getTextWidth(font, text) {
  let width = 0
  for (const char of text) width += getGlyph(font, char)[0].length + font.spacing
  return width - font.spacing
}

// Chama callback(coluna, linha) para cada pixel aceso do texto.
// É a base para desenhar o texto com contorno, sombra ou negrito.
export function forEachTextPixel(font, text, callback) {
  let cursor = 0
  for (const char of text) {
    const glyph = getGlyph(font, char)
    glyph.forEach((line, row) => {
      for (let col = 0; col < line.length; col++) {
        if (line[col] === '#') callback(cursor + col, row)
      }
    })
    cursor += glyph[0].length + font.spacing
  }
}

// Desenha o texto com uma cor, começando no canto superior esquerdo (x, y).
export function drawPixelText(ctx, font, text, x, y, color) {
  ctx.fillStyle = color
  forEachTextPixel(font, text, (col, row) => ctx.fillRect(x + col, y + row, 1, 1))
}
